#!/usr/bin/env python3
"""Build, check, and migrate the CRAV1 notes indexes (kit 1.61.0).

Notes live in docs/notes/YYYY-MM/YYYY-MM-DD-<slug>.md (month and date from the
SOURCE date). Each note starts with front matter:

    ---
    title: Source to target mapping
    kind: meeting
    source: meeting 2026-10-06 "Data sync"
    source_date: 2026-10-06        # or: none (then the import date is used)
    imported: 2026-10-16
    source_folder: docs/sources/2026-10-06-data-sync/
    used_by: [orders, billing]
    waiting_for: [orders-export]
    ---

Indexes are generated, never hand-edited:
    docs/notes/index.md           short top index, one row per month
    docs/notes/YYYY-MM/index.md   one row per note in that month

Usage (from the product repo root, or pass --root):
    python3 notes_index.py            rebuild every index
    python3 notes_index.py --check    exit 1 when an index differs from a rebuild
    python3 notes_index.py migrate-dry-run
                                      print planned moves, source fills, and link
                                      rewrites; write nothing (run this first)
    python3 notes_index.py migrate    one-time: move docs/notes/*.md into month
                                      folders by source date, fill source and
                                      source_folder from each Source: line, rewrite
                                      every markdown link to a moved note, rebuild.
                                      Safe to re-run (also fixes stale links and
                                      empty source fields after a manual move)
    python3 notes_index.py --selftest

Old notes without front matter are read gracefully: `Date:` line or filename
date, `Used by <slug>` and `Absorbed by <slug>` lines under `## Used by`.
Standard library only.
"""
import argparse, os, re, shutil, subprocess, sys, tempfile
from pathlib import Path

DATE = re.compile(r"(\d{4}-\d{2}-\d{2})")
MONTH_DIR = re.compile(r"^\d{4}-\d{2}$")
GEN = "<!-- Generated by notes_index.py from note front matter. Do not edit by hand. -->"


def parse_list(v):
    v = v.strip()
    if v.startswith("[") and v.endswith("]"):
        v = v[1:-1]
    return [x.strip().strip("'\"") for x in v.split(",") if x.strip()]


def read_note(path):
    text = path.read_text(encoding="utf-8")
    meta, body = {}, text
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end != -1:
            for line in text[4:end].splitlines():
                line = line.split(" #", 1)[0].rstrip()
                if ":" in line:
                    k, v = line.split(":", 1)
                    meta[k.strip()] = v.strip()
            body = text[end + 4:]
    title = meta.get("title", "").strip("'\"")
    if not title:
        m = re.search(r"^# (.+)$", body, re.M)
        title = m.group(1).strip() if m else path.stem
    used = parse_list(meta.get("used_by", ""))
    waiting = parse_list(meta.get("waiting_for", ""))
    absorbed = []
    for m in re.finditer(r"^(Used by|Absorbed by|Waiting for) ([\w.-]+)", body, re.M):
        kind, slug = m.group(1), m.group(2)
        if kind == "Used by" and slug not in used:
            used.append(slug)
        elif kind == "Absorbed by":
            absorbed.append(slug)
            if slug not in used:
                used.append(slug)
        elif kind == "Waiting for" and slug not in waiting:
            waiting.append(slug)
    sd = meta.get("source_date", "")
    if not DATE.fullmatch(sd or ""):
        m = re.search(r"^Date:\s*(\d{4}-\d{2}-\d{2})", body, re.M) or DATE.match(path.name)
        sd = m.group(1) if m else ""
    imported = meta.get("imported", "")
    return {
        "path": path, "title": title, "kind": meta.get("kind", ""),
        "source": meta.get("source", "").strip("'\""), "date": sd or imported,
        "dated": bool(sd), "imported": imported, "used_by": used,
        "waiting_for": waiting, "absorbed": absorbed,
    }


def note_files(notes):
    out = []
    for d in sorted(p for p in notes.iterdir() if p.is_dir() and (MONTH_DIR.match(p.name) or p.name == "undated")):
        out += sorted(p for p in d.glob("*.md") if p.name != "index.md")
    return out


def cell(s):
    return str(s).replace("|", "\\|")


def render(root):
    notes = root / "docs" / "notes"
    by_month = {}
    for f in note_files(notes):
        n = read_note(f)
        by_month.setdefault(f.parent.name, []).append(n)
    files = {}
    top = ["# Notes", "", GEN, "",
           "One folder per month of the source date. Open a month for its notes.", "",
           "| Month | Notes | Waiting for a parked spec |", "| --- | --- | --- |"]
    for month in sorted(by_month, reverse=True):
        ns = sorted(by_month[month], key=lambda n: (n["date"], n["path"].name))
        waiting = sum(1 for n in ns if n["waiting_for"])
        top.append(f"| [{month}]({month}/index.md) | {len(ns)} | {waiting} |")
        rows = [f"# Notes {month}", "", GEN, "",
                "| Title | Date | Kind | Source | Used by | Waiting for |",
                "| --- | --- | --- | --- | --- | --- |"]
        for n in ns:
            date = n["date"] or "not shown"
            if n["date"] and not n["dated"]:
                date += " (imported, no source date)"
            used = "; ".join(n["used_by"]) + (" (old: absorbed)" if n["absorbed"] else "")
            rows.append("| " + " | ".join(cell(x) for x in [
                f"[{n['title']}]({n['path'].name})", date, n["kind"], n["source"],
                used, "; ".join(n["waiting_for"])]) + " |")
        files[notes / month / "index.md"] = "\n".join(rows) + "\n"
    files[notes / "index.md"] = "\n".join(top) + "\n"
    return files


def build(root, check=False):
    notes = root / "docs" / "notes"
    if not notes.is_dir():
        print("no docs/notes/; nothing to index")
        return 0
    loose = [p for p in notes.glob("*.md") if p.name not in ("index.md", "README.md")]
    if loose:
        print("loose notes in docs/notes/ (run: notes_index.py migrate):")
        for p in loose:
            print("  ", p.relative_to(root))
        if check:
            return 1
    bad = 0
    for path, text in render(root).items():
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur == text:
            continue
        if check:
            print(f"{path.relative_to(root)} is stale; run notes_index.py")
            bad = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(root)}")
    if check and not bad:
        print("notes indexes match the note front matter")
    return bad


def git_add_date(root, path):
    try:
        out = subprocess.run(["git", "log", "--diff-filter=A", "--format=%as", "--", str(path)],
                             cwd=root, capture_output=True, text=True).stdout.split()
        return out[-1] if out else ""
    except OSError:
        return ""


SOURCE_LINE = re.compile(r"^Source:\s*(.+?)\s*$", re.M)
SOURCES_PATH = re.compile(r"(docs/sources/[\w./-]+?)/?(?=[\s`)\]]|$)")
TOKEN = re.compile(r"(?<![\w./:-])((?:\.{1,2}/)+[\w.\-/]*|[\w.-]+(?:/[\w.-]+)*\.md(?![\w/-])|docs/[\w.\-/]+)")
LINK_TARGET = re.compile(r"\]\(\s*<?([^)\s#>]+)")
SKIP_DIRS = {".git", "node_modules"}


def source_items(body):
    """Every Source: line, split into items: comma/semicolon lists on the
    line, and `- item` bullets right under an empty or list-style Source:."""
    lines = body.splitlines()
    items = []
    for i, line in enumerate(lines):
        m = re.match(r"^Source[s]?:\s*(.*?)\s*$", line)
        if not m:
            continue
        val = m.group(1)
        if val:
            items.append(val)
        j = i + 1
        while j < len(lines) and re.match(r"^\s*[-*]\s+\S", lines[j]):
            items.append(re.sub(r"^\s*[-*]\s+", "", lines[j]).strip())
            j += 1
    return items


def source_fields(text):
    """Mechanical, never guessed. source_folder is the first docs/sources/ path
    across all Source: lines and items; source is that line (or item) verbatim.
    When none points into docs/sources/, source is the first Source: line and
    source_folder is empty. No Source: line -> both empty."""
    body = text
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        body = text[end + 4:] if end != -1 else text
    items = source_items(body)
    if not items:
        return "", ""
    for it in items:
        f = SOURCES_PATH.search(it.replace("`", " "))
        if f:
            return it, f.group(1) + "/"
    return items[0], ""


def set_front(text, fields):
    """Fill empty or missing front-matter keys; never overwrite a value."""
    end = text.find("\n---", 4)
    lines = text[4:end].splitlines()
    have = {}
    for i, line in enumerate(lines):
        if ":" in line:
            have[line.split(":", 1)[0].strip()] = i
    changed = []
    for k, v in fields.items():
        if not v:
            continue
        if k in have:
            cur = lines[have[k]].split(":", 1)[1].strip()
            if cur:
                continue
            lines[have[k]] = f"{k}: {v}"
        else:
            lines.append(f"{k}: {v}")
        changed.append(k)
    return "---\n" + "\n".join(lines) + text[end:], changed


def md_files(root):
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in SKIP_DIRS and not (d.startswith(".") and dp == str(root))]
        for fn in fns:
            if fn.endswith(".md"):
                yield Path(dp) / fn


def plan(root):
    """Return moves, front-matter fills, and link rewrites. Writes nothing."""
    notes = root / "docs" / "notes"
    moves, fills = {}, {}
    if not notes.is_dir():
        return moves, fills, {}
    for f in sorted(notes.glob("*.md")):
        if f.name in ("index.md", "README.md"):
            continue
        n = read_note(f)
        text = f.read_text(encoding="utf-8")
        date = n["date"]
        src, folder = source_fields(text)
        if not text.startswith("---\n"):
            imported = git_add_date(root, f)
            fm = ["---", f"title: {n['title']}", "kind: " + (n["kind"] or "note"),
                  f"source: {src}", f"source_date: {date or 'none'}",
                  f"imported: {imported or date or 'unknown'}", f"source_folder: {folder}"]
            if n["used_by"]:
                fm.append("used_by: [" + ", ".join(n["used_by"]) + "]")
            if n["waiting_for"]:
                fm.append("waiting_for: [" + ", ".join(n["waiting_for"]) + "]")
            text = "\n".join(fm) + "\n---\n" + text
            if not date and imported:
                date = imported
            fills[f] = [k for k, v in (("source", src), ("source_folder", folder)) if v]
        else:
            text, ch = set_front(text, {"source": src, "source_folder": folder})
            if ch:
                fills[f] = ch
        dest = notes / (date[:7] if date else "undated") / f.name
        if dest.exists():
            print(f"skip {f.relative_to(root)}: {dest.relative_to(root)} exists")
            continue
        moves[f] = (dest, text)
    # notes already in month folders (manual migration): fill only
    for f in note_files(notes):
        text = f.read_text(encoding="utf-8")
        if text.startswith("---\n"):
            src, folder = source_fields(text)
            new, ch = set_front(text, {"source": src, "source_folder": folder})
            if ch:
                fills[f] = ch
                moves.setdefault(f, (f, new))
    # names of notes in month folders, for stale links after a manual move
    by_name = {}
    for f in note_files(notes):
        by_name.setdefault(f.name, []).append(f)
    for old, (dest, _) in moves.items():
        if dest != old:
            by_name.setdefault(old.name, []).append(dest)
    root = root.resolve()
    old_to_new = {o.resolve(): d.resolve() for o, (d, _) in moves.items() if d != o}

    rewrites = {}
    for f in md_files(root):
        f_old = Path(os.path.normpath(f.resolve()))
        f_new = old_to_new.get(f_old, f_old)
        text = moves[f][1] if f in moves else f.read_text(encoding="utf-8")
        out, changes = [], []
        pos = 0
        spans = {}
        for m in TOKEN.finditer(text):
            spans[m.start(1)] = (m.end(1), m.group(1))
        for m in LINK_TARGET.finditer(text):
            spans.setdefault(m.start(1), (m.end(1), m.group(1)))
        last_end = 0
        for start in sorted(spans):
            end, tok = spans[start]
            if start < last_end or not tok or tok in ("./", "../"):
                continue
            if "://" in tok or tok.startswith(("/", "mailto:", "#")) or "://" in text[max(0, start - 10):start]:
                continue
            slash = tok.endswith("/")
            core = tok.rstrip("/")
            repo_style = core.startswith("docs/")
            explicit_rel = core.startswith(("./", "../")) or bool(LINK_TARGET.match(text, max(0, start - 2)) and text[start - 2:start] == "](")
            target = Path(os.path.normpath(root / core if repo_style else f_old.parent / core))
            new_target = old_to_new.get(target)
            if new_target is None and not target.exists():
                if target.parent == (root / "docs" / "notes").resolve():
                    cands = [c for c in by_name.get(target.name, []) if c.resolve() != target]
                    if len(cands) == 1:
                        new_target = cands[0].resolve()
            if new_target is None:
                if f_new == f_old or repo_style:
                    continue
                if not (target.exists() or explicit_rel):
                    continue
                new_target = target  # moved file: rebase its own relative link
            if repo_style:
                rep_ = new_target.relative_to(root.resolve()).as_posix()
            else:
                rep_ = os.path.relpath(new_target, f_new.parent).replace(os.sep, "/")
                if core.startswith("./") and not rep_.startswith("."):
                    rep_ = "./" + rep_
            if slash:
                rep_ += "/"
            last_end = end
            if rep_ == tok:
                continue
            out.append(text[pos:start] + rep_)
            pos = end
            changes.append((tok, rep_))
        if changes:
            out.append(text[pos:])
            rewrites[f] = ("".join(out), changes)
    return moves, fills, rewrites


def migrate(root, dry_run=False):
    notes = root / "docs" / "notes"
    if not notes.is_dir():
        print("no docs/notes/; nothing to migrate")
        return 0
    moves, fills, rewrites = plan(root)
    tag = "would " if dry_run else ""
    rel = lambda p: p.relative_to(root).as_posix()
    for old, (dest, _) in moves.items():
        if dest != old:
            print(f"{tag}move {rel(old)} -> {rel(dest)}")
    for f, keys in fills.items():
        print(f"{tag}fill {', '.join(keys)} in {rel(f)} (from its Source: line)")
    for f, (_, ch) in rewrites.items():
        for a, b in ch:
            print(f"{tag}rewrite {rel(f)}: {a} -> {b}")
    if not (moves or rewrites):
        print("nothing to migrate")
    if dry_run:
        print("dry run: nothing written")
        return 0
    for f, (text, _) in rewrites.items():
        if f in moves:
            moves[f] = (moves[f][0], text)
        else:
            f.write_text(text, encoding="utf-8")
    for old, (dest, text) in moves.items():
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding="utf-8")
        if dest != old:
            old.unlink()
    changed = sorted({rel(f) for f in rewrites if f not in moves})
    if changed:
        print("files with rewritten links: " + ", ".join(changed))
    return build(root)


def selftest():
    with tempfile.TemporaryDirectory() as t:
        root = Path(t)
        notes = root / "docs" / "notes"
        notes.mkdir(parents=True)
        (notes / "index.md").write_text("| old | hand | index |\n")
        (notes / "2026-10-06-mapping.md").write_text(
            "# Mapping\n\nDate: 2026-10-06\n\nFrom email. \"x\"\n\nSource: docs/sources/2026-10-06-mail/\n\n"
            "See [other](2026-09-01-other.md) and [src](../sources/2026-10-06-mail/README.md).\n\n"
            "## Used by\n\nUsed by orders\nAbsorbed by orders\n")
        (notes / "2026-09-01-other.md").write_text("# Other\n\nDate: 2026-09-01\n\n## Used by\n")
        (root / "docs" / "sources" / "2026-10-06-mail").mkdir(parents=True)
        (root / "docs" / "sources" / "2026-10-06-mail" / "README.md").write_text(
            "Noted in [note](../../notes/2026-10-06-mapping.md).\n")
        spec = root / "docs" / "specs" / "retired" / "orders"
        spec.mkdir(parents=True)
        (spec / "spec.md").write_text("Full source: docs/notes/2026-10-06-mapping.md\n"
                                      "[n](../../../notes/2026-10-06-mapping.md)\n")
        before = {p: p.read_text() for p in root.rglob("*.md")}
        assert migrate(root, dry_run=True) == 0
        assert before == {p: p.read_text() for p in root.rglob("*.md")}, "dry run wrote"
        assert migrate(root) == 0
        m = notes / "2026-10" / "2026-10-06-mapping.md"
        mt = m.read_text()
        assert "source: docs/sources/2026-10-06-mail/" in mt and "source_folder: docs/sources/2026-10-06-mail/" in mt
        assert "(../2026-09/2026-09-01-other.md)" in mt and "(../../sources/2026-10-06-mail/README.md)" in mt
        st = (spec / "spec.md").read_text()
        assert "Full source: docs/notes/2026-10/2026-10-06-mapping.md" in st
        assert "(../../../notes/2026-10/2026-10-06-mapping.md)" in st
        assert "(../../notes/2026-10/2026-10-06-mapping.md)" in (
            root / "docs" / "sources" / "2026-10-06-mail" / "README.md").read_text()
        o = (notes / "2026-09" / "2026-09-01-other.md").read_text()
        assert "source: \n" in o and "source_folder: \n" in o, "no Source: line must stay empty"
        snap = {p: p.read_text() for p in root.rglob("*.md")}
        assert migrate(root) == 0
        assert snap == {p: p.read_text() for p in root.rglob("*.md")}, "not idempotent"
        # manual migration: file moved by hand, link left stale
        (notes / "2026-08").mkdir()
        (notes / "2026-08" / "2026-08-01-hand.md").write_text(
            "---\ntitle: Hand\nsource_date: 2026-08-01\nimported: 2026-10-16\n---\n# Hand\n\nSource: meeting 2026-08-01 \"Sync\"\n")
        (spec / "spec.md").write_text(st + "Full source: docs/notes/2026-08-01-hand.md\n")
        assert migrate(root) == 0
        assert "docs/notes/2026-08/2026-08-01-hand.md" in (spec / "spec.md").read_text()
        assert 'source: meeting 2026-08-01 "Sync"' in (notes / "2026-08" / "2026-08-01-hand.md").read_text()
        # round 2: rebase every relative link in a moved note; multi Source lines
        (root / "docs" / "sources" / "x").mkdir(parents=True)
        (root / "docs" / "sources" / "x" / "mail.txt").write_text("m")
        (notes / "2026-07-02-multi.md").write_text(
            "# Multi\n\nDate: 2026-07-02\n\nSource: meeting 2026-07-02 \"Kickoff\"\n"
            "Source: docs/sources/x/\n\n"
            "Folder [f](../sources/x/), file [t](../sources/x/mail.txt), bare ../sources/x/mail.txt, "
            "anchor [a](2026-09-01-other.md#top), url [u](https://e.com/a.md), root docs/sources/x/, [h](#local)\n")
        (notes / "2026-07-03-list.md").write_text(
            "---\ntitle: List\nsource: mail \"Hi\"\nsource_date: 2026-07-03\nimported: 2026-10-16\n---\n# List\n\n"
            "Sources:\n- mail \"Hi\"\n- docs/sources/x/mail.txt\n")
        (spec / "spec.md").write_text((spec / "spec.md").read_text() + "[m](../../../notes/2026-07-02-multi.md#part)\n")
        assert migrate(root) == 0
        mm = (notes / "2026-07" / "2026-07-02-multi.md").read_text()
        for want in ["(../../sources/x/)", "(../../sources/x/mail.txt)", "bare ../../sources/x/mail.txt",
                     "(../2026-09/2026-09-01-other.md#top)", "(https://e.com/a.md)", "root docs/sources/x/", "(#local)",
                     "source: docs/sources/x/", "source_folder: docs/sources/x/"]:
            assert want in mm, want
        lt = (notes / "2026-07" / "2026-07-03-list.md").read_text()
        assert 'source: mail "Hi"' in lt and "source_folder: docs/sources/x/" in lt, lt
        assert "(../../../notes/2026-07/2026-07-02-multi.md#part)" in (spec / "spec.md").read_text()
        snap = {p: p.read_text() for p in root.rglob("*.md")}
        assert migrate(root) == 0
        assert snap == {p: p.read_text() for p in root.rglob("*.md")}, "round 2 not idempotent"
        (notes / "2026-09" / "2026-09-30-call.md").write_text(
            "---\ntitle: Call\nkind: meeting\nsource: meeting 2026-09-30 \"Call\"\nsource_date: 2026-09-30\n"
            "imported: 2026-10-16\nused_by: [billing]\nwaiting_for: [orders-export]\n---\n# Call\n\nfull text\n")
        assert build(root, check=True) == 1
        assert build(root) == 0 and build(root, check=True) == 0
        top = (notes / "index.md").read_text()
        assert "[2026-09](2026-09/index.md) | 2 | 1" in top
        assert "old: absorbed" in (notes / "2026-10" / "index.md").read_text()
    print("selftest ok")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", nargs="?", choices=["build", "migrate", "migrate-dry-run"], default="build")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=".")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    root = Path(a.root).resolve()
    if a.command in ("migrate", "migrate-dry-run"):
        return migrate(root, dry_run=a.command == "migrate-dry-run")
    return build(root, a.check)


if __name__ == "__main__":
    sys.exit(main())
