#!/usr/bin/env python3
"""Generate the compact crav1-docs bundle and the repo-root llms.txt.

The human pages stay in docs/. An install reads the compact edition next to
the skills (crav1-docs/). Both come from the same sources: skills.yaml for
skill pages, the skills list, and guild routing; marks.yaml for the mark
lines in the data-layout page; the human Markdown for walkthroughs and
concepts. Nine always-read rule files are copied byte for byte.

  scripts/gen-compact-docs.py            write the Cursor bundle and llms.txt
  scripts/gen-compact-docs.py --check    exit non-zero when a committed copy drifts
  scripts/gen-compact-docs.py --stats    print token sizes and one sample page

Needs PyYAML (pip install pyyaml). The interpreter is python3 on this host
(docs/reference/running-scripts.md).
"""

