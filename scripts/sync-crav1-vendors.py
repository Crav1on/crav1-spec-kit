#!/usr/bin/env python3
"""Generate the Codex and Copilot trees from the Cursor drop-in.

  scripts/sync-crav1-vendors.py           write vendors/codex and vendors/copilot
  scripts/sync-crav1-vendors.py --check   exit non-zero if a committed tree is stale
  scripts/sync-crav1-vendors.py --lint    per-vendor rules (also run from kit-lint)

The trees are committed and no tool loads them. This release does not install
them and does not write a project's AGENTS.md. Generation is deterministic:
the same source bytes produce the same tree. Standard library only.

Layout, from the update-kit vendor table:
  Codex:   vendors/codex/.agents/skills/
  Copilot: vendors/copilot/.github/skills/
           vendors/copilot/.github/instructions/crav1.instructions.md
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DOCS_DIR = "crav1-docs"
NAME_RULE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
# Same lookbehind as vendor_prefix.py: a path such as crav1/crav1-help stays.
COMMAND = re.compile(r"(?<![A-Za-z0-9_./-])/crav1-")
HELP_DOCS_CURSOR = re.compile(r"^- Cursor drop-in: .*\n- Cursor plugin: .*\n", re.MULTILINE)
MARKER = "<!-- Generated by scripts/sync-crav1-vendors.py. Do not edit. -->"
RULE_LINE = "Read `../crav1-docs/reference/kit-rules.md` first."
CARD_LINE = (
    "If the host has no card tool, or allows fewer options, print the options "
    "as a numbered list with their choice words and wait for the reply."
)
RUN_NEXT_SCRIPTS = (
    "build_map.py",
    "build_walk.py",
    "design_run.py",
    "ending.py",
    "explain_tech.py",
    "permission_block.py",
    "plan_check.py",
    "repo_sync.py",
    "sweep_progress.py",
    "update_kit.py",
    "walk_ending.py",
    "walk_progress.py",
)
TEXT_SUFFIXES = {".md", ".mdc", ".txt", ".yml", ".yaml"}
KEEP_KEYS = ("name", "description", "disable-model-invocation")
AUTO_START = {"crav1-help", "crav1-update-kit"}


def kit_version(root: Path) -> str:
    path = root / "plugins/crav1/.cursor-plugin/plugin.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    version = str(data.get("version") or "").strip()
    if not version:
        raise SystemExit(f"no version in {path}")
    return version


def load_vendors(root: Path) -> dict:
    path = root / ".cursor/skills/crav1/crav1-update-kit/vendors.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = data.get("vendors") or {}
    out = {}
    for name in ("codex", "copilot"):
        row = rows.get(name)
        if not isinstance(row, dict):
            raise SystemExit(f"vendors.json has no {name} row")
        out[name] = row
    return out


def split_frontmatter(text: str) -> tuple[str | None, str]:
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return None, text
    return text[4:end], text[end + 5 :]


def parse_frontmatter(fm: str) -> list[tuple[str, str]]:
    entries: list[tuple[str, str]] = []
    key = None
    buf: list[str] = []
    for line in fm.splitlines():
        if line and not line[0].isspace() and re.match(r"^[A-Za-z0-9_-]+:", line):
            if key is not None:
                entries.append((key, "\n".join(buf)))
            key = line.split(":", 1)[0]
            buf = [line]
        elif key is not None:
            buf.append(line)
    if key is not None:
        entries.append((key, "\n".join(buf)))
    return entries


def frontmatter_value(block: str) -> str:
    _, _, rest = block.partition(":")
    return rest.strip()


def render_frontmatter(entries: list[tuple[str, str]], vendor: str, version: str) -> str:
    by = {key: block for key, block in entries}
    if "name" not in by or "description" not in by:
        raise SystemExit("SKILL.md frontmatter needs name and description")
    lines = [by["name"], by["description"], "license: MIT"]
    if "disable-model-invocation" in by:
        lines.append(by["disable-model-invocation"])
    lines.append("metadata:")
    lines.append(f"  crav1-vendor: {vendor}")
    lines.append(f"  crav1-version: {version}")
    return "\n".join(lines)


def is_command_only(entries: list[tuple[str, str]]) -> bool:
    for key, block in entries:
        if key == "disable-model-invocation":
            return frontmatter_value(block).lower() == "true"
    return False


def help_docs_line(text: str, vendor: str, skills_rel: str) -> str:
    if vendor == "codex":
        line = f"- Codex: `{skills_rel}/crav1-docs/`.\n"
    else:
        line = f"- GitHub Copilot: `{skills_rel}/crav1-docs/`.\n"
    updated, count = HELP_DOCS_CURSOR.subn(lambda _m: line, text)
    if count != 1:
        raise SystemExit(f"crav1-help SKILL.md: expected one Cursor docs-folder pair, found {count}")
    return updated


def add_vendor_flag(text: str, vendor: str) -> str:
    """Append --vendor to a Run next script call. Mentions without a call stay."""
    names = "|".join(re.escape(name) for name in RUN_NEXT_SCRIPTS)
    span = re.compile(r"`([^`\n]*\b(?:" + names + r")\b[^`\n]*)`")

    def repl(match: re.Match) -> str:
        body = match.group(1)
        if "--vendor" in body:
            return match.group(0)
        stripped = body.strip()
        call = bool(re.match(r"^(?:<|python|scripts/|\./)", stripped)) or bool(
            re.match(r"^(?:[A-Za-z0-9_./-]+/)?" + "(?:" + names + r")\b", stripped)
        )
        if not call and "--" not in body:
            return match.group(0)
        if not call and not re.search(r"\b(?:" + names + r")\b", body):
            return match.group(0)
        if not call:
            return match.group(0)
        return "`" + body.rstrip() + f" --vendor {vendor}`"

    text = span.sub(repl, text)
    names_re = re.compile(r"\b(?:" + names + r")\b")
    out = []
    for line in text.splitlines():
        stripped = line.strip()
        if (
            names_re.search(stripped)
            and "--vendor" not in stripped
            and not stripped.startswith("`")
            and (stripped.startswith(("python", "scripts/", "<")) or bool(re.match(r"^[A-Za-z0-9_./-]+\.py\b", stripped)))
            and ("--" in stripped or re.search(r"\.py\s+\S", stripped))
        ):
            line = line.rstrip() + f" --vendor {vendor}"
        out.append(line)
    suffix = "\n" if text.endswith("\n") else ""
    return "\n".join(out) + suffix


def rewrite_paths(text: str, skills_rel: str) -> str:
    skills_rel = skills_rel.rstrip("/")
    # Other hosts' skill folders become this vendor's folder, so a generated
    # copy does not tell that host to read another vendor's tree.
    for old, new in (
        (".cursor/skills/crav1/", skills_rel + "/"),
        (".cursor/agents/", skills_rel + "/crav1-docs/agents/"),
        (".cursor/agent-assets/", skills_rel + "/crav1-docs/agent-assets/"),
        (".claude/skills/", skills_rel + "/"),
        (".github/skills/", skills_rel + "/"),
        (".agents/skills/", skills_rel + "/"),
    ):
        if old != new:
            text = text.replace(old, new)
    return text


def rewrite_prefix(text: str, vendor: str) -> str:
    if vendor != "codex":
        return text
    return COMMAND.sub("$crav1-", text)


def transform_skill(text: str, vendor: str, version: str, skills_rel: str) -> str:
    fm, body = split_frontmatter(text)
    if fm is None:
        raise SystemExit("SKILL.md is missing frontmatter")
    entries = parse_frontmatter(fm)
    rendered = render_frontmatter(entries, vendor, version)
    if not body.startswith("\n"):
        body = "\n" + body
    body = "\n" + RULE_LINE + "\n\n" + MARKER + "\n" + body
    text = "---\n" + rendered + "\n---\n" + body
    if "name: crav1-help\n" in rendered.split("metadata:", 1)[0]:
        text = help_docs_line(text, vendor, skills_rel)
    text = rewrite_paths(text, skills_rel)
    text = rewrite_prefix(text, vendor)
    return add_vendor_flag(text, vendor)


def transform_text(path: Path, text: str, vendor: str, skills_rel: str) -> str:
    if path.name == "vendors.json":
        return text
    # The docs bundle names every host on purpose (open-skill-file.md keeps
    # the Cursor and Claude paths). Skill files do not.
    if DOCS_DIR not in path.parts:
        text = rewrite_paths(text, skills_rel)
    if path.suffix.lower() in {".md", ".mdc", ".yml", ".yaml"}:
        text = rewrite_prefix(text, vendor)
        if path.suffix.lower() == ".md":
            text = add_vendor_flag(text, vendor)
    return text


def is_text(path: Path) -> bool:
    if path.suffix.lower() not in TEXT_SUFFIXES and path.name != "vendors.json":
        return False
    data = path.read_bytes()
    return b"\0" not in data


def kit_rules_body(cursor: Path, vendor: str, skills_rel: str) -> str:
    text = (cursor / "rules" / "crav1.mdc").read_text(encoding="utf-8")
    _fm, body = split_frontmatter(text)
    body = rewrite_paths(body, skills_rel)
    body = rewrite_prefix(body, vendor)
    return body.strip() + "\n"


def generate_one(root: Path, vendor: str, row: dict, version: str) -> Path:
    skills_rel = str(row["skills"]).rstrip("/")
    tree = root / str(row["tree"])
    cursor = root / ".cursor"
    skills_src = cursor / "skills" / "crav1"
    if not skills_src.is_dir():
        raise SystemExit(f"missing Cursor source: {skills_src}")
    if tree.exists():
        shutil.rmtree(tree)
    dest_skills = tree / skills_rel
    dest_skills.mkdir(parents=True)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
    for skill_dir in sorted(p for p in skills_src.iterdir() if p.is_dir() and p.name != DOCS_DIR):
        shutil.copytree(skill_dir, dest_skills / skill_dir.name, ignore=ignore)
    docs_src = skills_src / DOCS_DIR
    if docs_src.is_dir():
        shutil.copytree(docs_src, dest_skills / DOCS_DIR, ignore=ignore)
    agents_src = cursor / "agents"
    if agents_src.is_dir():
        agent_dest = dest_skills / DOCS_DIR / "agents"
        agent_dest.mkdir(parents=True, exist_ok=True)
        for agent in sorted(agents_src.glob("crav1-*.md")):
            shutil.copy2(agent, agent_dest / agent.name)
    assets_src = cursor / "agent-assets"
    if assets_src.is_dir():
        shutil.copytree(assets_src, dest_skills / DOCS_DIR / "agent-assets", ignore=ignore, dirs_exist_ok=True)

    # Frontmatter and the first line need the kit version. Transform skills
    # here, then the rest of the tree (docs included) for paths and prefix.
    for skill_md in sorted(dest_skills.glob("*/SKILL.md")):
        text = skill_md.read_text(encoding="utf-8")
        skill_md.write_text(transform_skill(text, vendor, version, skills_rel), encoding="utf-8", newline="\n")
    for path in sorted(p for p in dest_skills.rglob("*") if p.is_file() and p.name != "SKILL.md"):
        if not is_text(path):
            continue
        text = path.read_text(encoding="utf-8")
        updated = transform_text(path, text, vendor, skills_rel)
        if updated != text:
            path.write_text(updated, encoding="utf-8", newline="\n")

    rules = kit_rules_body(cursor, vendor, skills_rel)
    (dest_skills / DOCS_DIR / "reference" / "kit-rules.md").write_text(rules, encoding="utf-8", newline="\n")
    cards = dest_skills / DOCS_DIR / "reference" / "question-cards.md"
    if cards.is_file() and CARD_LINE not in cards.read_text(encoding="utf-8"):
        with cards.open("a", encoding="utf-8", newline="\n") as handle:
            handle.write("\n" + CARD_LINE + "\n")

    for skill_md in sorted(dest_skills.glob("*/SKILL.md")):
        fm, _body = split_frontmatter(skill_md.read_text(encoding="utf-8"))
        entries = parse_frontmatter(fm or "")
        name = frontmatter_value(dict(entries).get("name", "name:"))
        if vendor != "codex" or name in AUTO_START or not is_command_only(entries):
            continue
        folder = skill_md.parent / "agents"
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "openai.yaml").write_text(
            "policy:\n  allow_implicit_invocation: false\n",
            encoding="utf-8",
            newline="\n",
        )

    if vendor == "copilot":
        instructions = tree / ".github/instructions/crav1.instructions.md"
        instructions.parent.mkdir(parents=True, exist_ok=True)
        body = (
            "---\napplyTo: \"**\"\n---\n\n"
            "Read `.github/skills/crav1-docs/reference/kit-rules.md` first.\n\n"
            + rules
        )
        instructions.write_text(body, encoding="utf-8", newline="\n")

    leaked = list(tree.rglob("AGENTS.md")) + list(tree.rglob("kit-maintainer.mdc"))
    if leaked:
        raise SystemExit(f"refusing to write {leaked}")
    return tree


def generate(root: Path) -> None:
    version = kit_version(root)
    for name, row in load_vendors(root).items():
        generate_one(root, name, row, version)
        print(f"Synced .cursor/ → {row['tree']} ({name})")


def check(root: Path) -> int:
    failed = False
    with tempfile.TemporaryDirectory(prefix="crav1-vendors-") as tmp:
        fresh_root = Path(tmp)
        # generate_one writes under root / tree. Build a stand-in root that
        # has the Cursor source and the plugin version, and generate there.
        standin = fresh_root / "src"
        standin.mkdir()
        for rel in (".cursor", "plugins"):
            shutil.copytree(root / rel, standin / rel, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        generate(standin)
        for name, row in load_vendors(root).items():
            fresh = standin / str(row["tree"])
            committed = root / str(row["tree"])
            if not committed.exists():
                print(f"Committed {row['tree']} is missing.", file=sys.stderr)
                print("Run scripts/sync-crav1-vendors.py.", file=sys.stderr)
                failed = True
                continue
            result = subprocess.run(["diff", "-ru", str(fresh), str(committed)], check=False)
            if result.returncode != 0:
                print(f"Committed {row['tree']} does not match a fresh generate.", file=sys.stderr)
                print("Run scripts/sync-crav1-vendors.py.", file=sys.stderr)
                failed = True
            else:
                print(f"{row['tree']} matches a fresh generate")
    return 1 if failed else 0


def skill_names(root: Path) -> list[str]:
    skills = root / ".cursor/skills/crav1"
    return sorted(
        path.name for path in skills.iterdir() if path.is_dir() and (path / "SKILL.md").is_file() and path.name != DOCS_DIR
    )


def _fm_keys(text: str) -> set[str]:
    fm, _body = split_frontmatter(text)
    if fm is None:
        return set()
    return {key for key, _block in parse_frontmatter(fm)}


def lint(root: Path) -> list[str]:
    """Per-vendor rules. crav1-docs is the shared docs bundle and still names every host."""
    problems: list[str] = []
    version = kit_version(root)
    expected = skill_names(root)
    source_only = {}
    for name in expected:
        text = (root / ".cursor/skills/crav1" / name / "SKILL.md").read_text(encoding="utf-8")
        fm, _body = split_frontmatter(text)
        source_only[name] = is_command_only(parse_frontmatter(fm or ""))
    command_only = sorted(name for name, flag in source_only.items() if flag)
    if set(command_only) & AUTO_START:
        problems.append("command-only set includes an auto-start skill")
    for vendor, row in load_vendors(root).items():
        tree = root / str(row["tree"])
        skills_rel = str(row["skills"]).rstrip("/")
        skills = tree / skills_rel
        label = str(row["tree"])
        if not skills.is_dir():
            problems.append(f"{label}: missing {skills_rel}")
            continue
        found = sorted(path.name for path in skills.iterdir() if path.is_dir() and path.name != DOCS_DIR)
        if found != expected:
            missing = sorted(set(expected) - set(found))
            extra = sorted(set(found) - set(expected))
            problems.append(f"{label}: skills {len(found)}/{len(expected)} missing={missing[:3]} extra={extra[:3]}")
        prefix = "$" if vendor == "codex" else "/"
        other_prefixes = {
            "codex": (".cursor/skills", ".claude/skills", ".github/skills"),
            "copilot": (".cursor/skills", ".claude/skills", ".agents/skills"),
        }[vendor]
        yaml_count = 0
        for name in expected:
            skill_md = skills / name / "SKILL.md"
            if not skill_md.is_file():
                continue
            text = skill_md.read_text(encoding="utf-8")
            fm, body = split_frontmatter(text)
            keys = _fm_keys(text)
            allowed = {"name", "description", "license", "disable-model-invocation", "metadata"}
            if keys - allowed:
                problems.append(f"{label}/{name}: frontmatter keys {sorted(keys - allowed)}")
            if "license" not in keys or "metadata" not in keys:
                problems.append(f"{label}/{name}: missing license or metadata")
            disabled = any(
                key == "disable-model-invocation" and frontmatter_value(block).lower() == "true"
                for key, block in parse_frontmatter(fm or "")
            )
            if disabled != (name in command_only):
                problems.append(f"{label}/{name}: disable-model-invocation does not match the source")
            if f"crav1-vendor: {vendor}" not in (fm or "") or f"crav1-version: {version}" not in (fm or ""):
                problems.append(f"{label}/{name}: metadata is not {vendor} {version}")
            described = ""
            for key, block in parse_frontmatter(fm or ""):
                if key == "description":
                    described = block
                if key == "name" and frontmatter_value(block) != name:
                    problems.append(f"{label}/{name}: name is not the folder")
            if not NAME_RULE.match(name) or len(name) > 64:
                problems.append(f"{label}/{name}: name breaks the Agent Skills rule")
            if len(described) > 1024:
                problems.append(f"{label}/{name}: description is {len(described)} characters")
            first = body.lstrip("\n").splitlines()[0] if body.strip() else ""
            if first != RULE_LINE:
                problems.append(f"{label}/{name}: first line is not the kit-rules line")
            if MARKER not in text:
                problems.append(f"{label}/{name}: missing generated header")
            yaml = skills / name / "agents" / "openai.yaml"
            if vendor == "codex":
                if name in command_only:
                    yaml_count += 1
                    if not yaml.is_file() or "allow_implicit_invocation: false" not in yaml.read_text(encoding="utf-8"):
                        problems.append(f"{label}/{name}: missing openai.yaml policy")
                elif yaml.exists():
                    problems.append(f"{label}/{name}: openai.yaml on an auto-start skill")
            elif yaml.exists():
                problems.append(f"{label}/{name}: openai.yaml is Codex only")
        if vendor == "codex" and yaml_count != len(command_only):
            problems.append(f"{label}: {yaml_count} openai.yaml files, expected {len(command_only)}")
        if vendor == "copilot":
            instructions = tree / ".github/instructions/crav1.instructions.md"
            inst = instructions.read_text(encoding="utf-8") if instructions.is_file() else ""
            if 'applyTo: "**"' not in inst:
                problems.append(f"{label}: missing .github/instructions/crav1.instructions.md")
        if list(tree.rglob("AGENTS.md")):
            problems.append(f"{label}: wrote AGENTS.md")
        names_re = re.compile(r"\b(?:" + "|".join(re.escape(n) for n in RUN_NEXT_SCRIPTS) + r")\b")
        for path in sorted(skills.rglob("*.md")):
            if DOCS_DIR in path.parts:
                continue
            file_text = path.read_text(encoding="utf-8")
            rel = path.relative_to(tree).as_posix()
            if vendor == "codex" and COMMAND.search(file_text):
                problems.append(f"{label}/{rel}: contains a /crav1- command")
            if vendor != "codex" and "$crav1-" in file_text:
                problems.append(f"{label}/{rel}: contains a $crav1- command")
            for needle in other_prefixes:
                if needle in file_text:
                    problems.append(f"{label}/{rel}: contains {needle}")
                    break
            for span in re.findall(r"`([^`\n]+)`", file_text):
                if names_re.search(span) and "--" in span and f"--vendor {vendor}" not in span:
                    if re.search(r"\.py\b", span):
                        problems.append(f"{label}/{rel}: Run next call missing --vendor {vendor}")
                        break
        if prefix != ("$" if vendor == "codex" else "/"):
            problems.append(f"{label}: prefix {prefix}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=None)
    parser.add_argument("--check", action="store_true", help="exit non-zero if a committed tree is stale")
    parser.add_argument("--lint", action="store_true", help="per-vendor lint rules")
    args = parser.parse_args(argv)
    root = (args.root or Path(__file__).resolve().parent.parent).resolve()
    if args.lint:
        found = lint(root)
        for item in found:
            print("FAIL  " + item)
        print(f"vendor lint: {len(found)} problem(s)")
        return 1 if found else 0
    if args.check:
        return check(root)
    generate(root)
    found = lint(root)
    if found:
        for item in found:
            print("FAIL  " + item, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
