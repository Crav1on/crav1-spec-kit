#!/usr/bin/env python3
"""Generate the skills reference from docs/reference/skills.yaml.

  scripts/gen-skill-docs.py          write docs/reference/skills.md and
                                     docs/reference/skills/crav1-<name>.md
  scripts/gen-skill-docs.py --check  exit non-zero when a page is stale, a page
                                     is extra, or the data file is out of line
                                     with the skill folders, the subagents, or
                                     the routing block;
                                     also writes docs/guild-routing.md (1.107.0)

Needs PyYAML (pip install pyyaml).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is missing. Install it with: python3 -m pip install pyyaml")

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs/reference/skills.yaml"
TABLE = ROOT / "docs/reference/skills.md"
PAGES = ROOT / "docs/reference/skills"
SKILLS_DIR = ROOT / ".cursor/skills/crav1"
AGENTS_DIR = ROOT / ".cursor/agents"
ROUTING = ROOT / "docs/guild-routing.md"

GENERATED = (
    "<!-- Generated by scripts/gen-skill-docs.py from docs/reference/skills.yaml. "
    "Do not edit by hand. -->"
)
LANE_KEYS = {"specify": "specify", "plan": "plan", "build": "build", "cross-cutting": "cross_cutting"}
CMD = re.compile(r"/crav1-[a-z0-9-]+")
AGENT = re.compile(r"crav1-[a-z0-9-]+-agent")


def cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def link_commands(text: str, names: set[str], prefix: str) -> str:
    """Link `/crav1-x` (with or without backticks) to its page."""

    def repl(m: re.Match[str]) -> str:
        raw = m.group(0)
        name = raw.strip("`")[1:]
        if name not in names:
            return raw
        return f"[`/{name}`]({prefix}{name}.md)"

    return re.sub(r"`?/crav1-[a-z0-9-]+`?", repl, text)


def calls_cell(text: str) -> str:
    found: list[str] = []
    for tok in re.findall(r"/crav1-[a-z0-9-]+|crav1-[a-z0-9-]+-agent", text or ""):
        if tok not in found:
            found.append(tok)
    return ", ".join(f"`{t}`" for t in found) if found else "—"


def load() -> dict:
    return yaml.safe_load(DATA.read_text(encoding="utf-8"))


def validate(data: dict) -> list[str]:
    errors: list[str] = []
    skills = data["skills"]
    names = [s["name"] for s in skills]
    lanes = {lane["id"]: lane for lane in data["lanes"]}
    if len(names) != len(set(names)):
        errors.append("skills.yaml lists a skill twice")
    folders = sorted(p.name for p in SKILLS_DIR.iterdir() if (p / "SKILL.md").is_file())
    for f in folders:
        if f not in names:
            errors.append(f"skill folder {f} is not in docs/reference/skills.yaml")
    for n in names:
        if n not in folders:
            errors.append(f"skills.yaml lists {n}, but .cursor/skills/crav1/{n}/SKILL.md is missing")
    agents = sorted(p.stem for p in AGENTS_DIR.glob("crav1-*.md"))
    sub_names = [s["name"] for s in data["subagents"]]
    for a in agents:
        if a not in sub_names:
            errors.append(f"subagent {a} is not in docs/reference/skills.yaml")
    for a in sub_names:
        if a not in agents:
            errors.append(f"skills.yaml lists subagent {a}, but .cursor/agents/{a}.md is missing")
    starters = set(data["starter_options"])
    routing = data.get("routing") or {}
    if set(routing.get("starters_runs_when", {})) != starters:
        errors.append("routing.starters_runs_when must name exactly the starter_options")
    lane_of = {x["name"]: x["lane"] for x in skills}
    for lid, lane in (routing.get("lanes") or {}).items():
        for n in lane.get("skills", {}):
            if lane_of.get(n) != lid:
                errors.append(f"routing.lanes.{lid} has text for {n}, whose lane is {lane_of.get(n)}")
    for s in skills:
        n = s["name"]
        for q in s.get("choice_words") or []:
            body = (SKILLS_DIR / n / "SKILL.md").read_text(encoding="utf-8") if (SKILLS_DIR / n / "SKILL.md").is_file() else ""
            for w in q.get("words") or []:
                if f"`{w['word']}`" not in body:
                    errors.append(f"{n}: choice word {w['word']!r} is not listed in its SKILL.md")
        if s["lane"] not in lanes:
            errors.append(f"{n}: unknown lane {s['lane']}")
            continue
        if s["group"] not in lanes[s["lane"]]["groups"]:
            errors.append(f"{n}: group {s['group']} is not a group of lane {s['lane']}")
        if bool(s["starter"]) != (n in starters):
            errors.append(f"{n}: starter flag differs from starter_options")
        w = s.get("walkthrough")
        if w and not (ROOT / w).is_file():
            errors.append(f"{n}: walkthrough {w} does not exist")
        elif w and not re.search(rf"\]\((?:\./)?reference/skills/{re.escape(n)}\.md[)#]", (ROOT / w).read_text(encoding="utf-8")):
            errors.append(f"{n}: walkthrough {w} does not link back to reference/skills/{n}.md")
        for key in ("purpose", "use_when", "reads", "writes", "first_prompt", "since", "stage"):
            if not s.get(key):
                errors.append(f"{n}: {key} is empty")
        pb = s.get("prompt_budget")
        if not isinstance(pb, int) or isinstance(pb, bool) or pb < 0:
            errors.append(f"{n}: prompt_budget must be a whole number, 0 or more")
        extra = s.get("in_depth", [])
        if not isinstance(extra, list) or not all(isinstance(p, str) and p.strip() for p in extra):
            errors.append(f"{n}: in_depth must be a list of paragraphs")
        for key in ("reads", "writes"):
            if not s.get("table", {}).get(key):
                errors.append(f"{n}: table.{key} is empty")
    for a in data["subagents"]:
        if a["lane"] not in lanes:
            errors.append(f"{a['name']}: unknown lane {a['lane']}")
    return errors


def walk_link(s: dict, prefix: str) -> str:
    w = s.get("walkthrough")
    if not w:
        return "reference only"
    path = Path(w)
    title = path.stem
    for line in (ROOT / w).read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
            break
    return f"[{title}]({prefix}{path.name})"


def render_table(data: dict) -> str:
    names = {s["name"] for s in data["skills"]}
    by_name = {s["name"]: s for s in data["skills"]}
    out = [GENERATED, "", "# Skills reference", ""]
    out += [
        "Every `/crav1-…` command and every subagent in the kit, grouped by lane. Each command says what it reads and what it writes. Writes lists every side effect, so anything not listed is left alone.",
        "",
        "Lanes (Specify, Plan, Build, Cross-cutting) are the routing authority, the same as [guild routing](../guild-routing.md). Groups inside a lane are reading aids. Each command links to its own page with the full behavior. Runs by itself lists the skills and subagents a command calls; naming a next command is not a call. A walkthrough is a step-by-step page; reference only means the command has no walkthrough of its own.",
        "",
        "Generated from [skills.yaml](skills.yaml). To change a row, edit that file and run `scripts/gen-skill-docs.py`.",
        "",
        "## Starters",
        "",
        "When the user asks for startup options, these six are the only ways in. That ask names the list. It does not run a skill and does not move work into a lane. Each starter still follows its own rules. Every other skill is a later skill.",
        "",
        "| Command | Lane | Use when |",
        "| --- | --- | --- |",
    ]
    lane_title = {lane["id"]: lane["title"] for lane in data["lanes"]}
    for n in data["starter_options"]:
        s = by_name[n]
        out.append(f"| [`/{n}`](skills/{n}.md) | {lane_title[s['lane']]} | {cell(s['use_when'])} |")
    header = "| Command | Starter | Use when | Reads | Writes | You run next | Runs by itself | Walkthrough |"
    sep = "| --- | --- | --- | --- | --- | --- | --- | --- |"
    for lane in data["lanes"]:
        out += ["", f"## {lane['title']}"]
        for group in lane["groups"]:
            rows = [s for s in data["skills"] if s["lane"] == lane["id"] and s["group"] == group]
            if not rows:
                continue
            out += ["", f"### {lane['title']}: {group}", "", header, sep]
            for s in rows:
                nxt = "; ".join(s.get("you_run_next") or []) or "—"
                out.append(
                    "| "
                    + " | ".join(
                        [
                            f"[`/{s['name']}`](skills/{s['name']}.md)",
                            "yes" if s["starter"] else "—",
                            cell(s["use_when"]),
                            cell(s["table"]["reads"]),
                            cell(s["table"]["writes"]),
                            cell(link_commands(nxt, names, "skills/")),
                            calls_cell(s.get("runs_by_itself", "")),
                            walk_link(s, "../"),
                        ]
                    )
                    + " |"
                )
    out += [
        "",
        "## Subagents",
        "",
        "A subagent is an isolated worker that a skill or the user starts. Reviewers write nothing. Writers change only what is listed.",
        "",
        "| Subagent | Lane | Started by | Writes | Purpose |",
        "| --- | --- | --- | --- | --- |",
    ]
    for a in data["subagents"]:
        out.append(
            f"| `{a['name']}` | {lane_title[a['lane']]} | {cell(link_commands(a['started_by'], names, 'skills/'))} | {cell(a['writes'])} | {cell(a['purpose'])} |"
        )
    out += ["", "Subagent details:", ""]
    for a in data["subagents"]:
        line = f"- `{a['name']}`. Reads: {a['reads']} Writes: {a['writes']}. Leaves alone: {a['leaves_alone']}"
        if a.get("calls"):
            line += f" Calls: {a['calls']}"
        line += f" Since {a['since']}."
        out.append(link_commands(" ".join(line.split()), names, "skills/"))
    out.append("")
    return "\n".join(out)


def render_page(s: dict, data: dict) -> str:
    names = {x["name"] for x in data["skills"]}
    lane_title = {lane["id"]: lane["title"] for lane in data["lanes"]}
    n = s["name"]
    lk = lambda t: link_commands(" ".join(str(t).split()), names, "")  # noqa: E731
    out = [GENERATED, "", f"# /{n}", ""]
    walk = walk_link(s, "../../")
    out.append(f"[All skills](../skills.md) · Walkthrough: {walk} · Playbook: [`SKILL.md`](../../../.cursor/skills/crav1/{n}/SKILL.md)")
    out += ["", "## Purpose", "", lk(s["purpose"])]
    for para in s.get("in_depth") or []:
        out += ["", lk(para)]
    runs = s["use_when"].rstrip(".") + "."
    if s.get("choice_words"):
        out += ["", "## Choice words", "", "Exact words for bots and scripted runs (no `--flags`). A word in the invocation takes that choice without asking. A headless or bot run with no word stops and names the valid words.", "", "| Question | Word | Means |", "| --- | --- | --- |"]
        for q in s["choice_words"]:
            for w in q["words"]:
                out.append(f"| {q['question']} | `{w['word']}` | {w['means']} |")
        for q in s["choice_words"]:
            if q.get("note"):
                out += ["", lk(q["note"])]
    out += ["", "## Runs when", "", lk(runs) + (" " + lk(s["called_by"]) if s.get("called_by") else "")]
    if s["starter"]:
        out += ["", "This is one of the six starter options. Asking for startup options names it and does not run it."]
    pb = s["prompt_budget"]
    out += ["", "## Prompts", "", f"Prompt budget: {pb} ({'asks nothing' if pb == 0 else 'the most prompts in one run, the closing yes included'}). A prompt may hold several questions. See the asking rule in `crav1.mdc`."]
    out += ["", "## Reads", "", f"In short: {lk(s['table']['reads'])}.", "", lk(s["reads"])]
    out += ["", "## Writes", "", f"In short: {lk(s['table']['writes'])}.", "", lk(s["writes"])]
    out += ["", "## Does not", ""]
    out.append(lk(s.get("leaves_alone") or "Nothing beyond what Writes lists is changed."))
    if s.get("exceptions"):
        out += ["", "Limits and exceptions: " + lk(s["exceptions"])]
    out += ["", "## You run next / Runs by itself", ""]
    nxt = "; ".join(s.get("you_run_next") or []) or "Nothing in particular."
    out.append(f"- You run next: {lk(nxt)}")
    out.append(f"- Runs by itself: {lk(s.get('runs_by_itself') or 'Calls no skill.')}")
    out += ["", "## Lane and group", "", f"Lane: {lane_title[s['lane']]}. Group: {s['group']}. Starter option: {'yes' if s['starter'] else 'no'}. Routing: [guild routing](../../guild-routing.md)."]
    out += ["", "## Stage and since", "", f"Stage: {s['stage']}. Since: {s['since']} ([changelog](../../../CHANGELOG.md))."]
    out += ["", "## First prompt", "", "```text", s["first_prompt"].rstrip(), "```"]
    out += ["", "## Walkthrough", ""]
    if s.get("walkthrough"):
        out.append(f"Step by step: {walk_link(s, '../../')}.")
    else:
        out.append("Reference only. This command has no walkthrough page of its own.")
    out.append("")
    return "\n".join(out)


def render_index(data: dict) -> str:
    """Small lookup /crav1-help reads first (1.106.0): one line per skill, so help opens one page, not skills.yaml."""
    out = ["# Generated by scripts/gen-skill-docs.py from skills.yaml. Do not edit.",
           "# /crav1-help reads this first, then only reference/skills/<name>.md for the skill it needs.",
           "skills:"]
    for s in data["skills"]:
        purpose = " ".join(str(s["purpose"]).split()).replace('"', "'")
        out += [f"  {s['name']}:", f"    lane: {s['lane']}", f"    starter: {str(bool(s.get('starter'))).lower()}",
                f"    page: reference/skills/{s['name']}.md", f'    purpose: "{purpose}"']
    out += ["concepts: concepts/", "workflow: reference/workflow.yaml", "changelog: CHANGELOG.md  # only for what is new or a release question", ""]
    return "\n".join(out)


def render_routing(data: dict) -> str:
    """docs/guild-routing.md (1.107.0): lanes from skills[].lane and subagents[].lane, prose from routing."""
    r = data["routing"]
    out = ["# Guild routing", "", GENERATED, ""]
    out += [p + "\n" for p in r["intro"]]
    out += ["## Starter options", "", r["starters_intro"], "", "| Starter | Runs when |", "| --- | --- |"]
    out += [f"| `/{n}` | {r['starters_runs_when'][n]} |" for n in data["starter_options"]]
    out += [""] + [p + "\n" for p in r["starters_outro"]]
    for lane in data["lanes"]:
        lid = lane["id"]
        lr = r["lanes"].get(lid, {})
        out += [f"## {lane['title']}", "", "| Kind | Name |", "| --- | --- |"]
        out += [f"| Skill | `/{x['name']}` |" for x in data["skills"] if x["lane"] == lid]
        out += [f"| Subagent | `{x['name']}` |" for x in data["subagents"] if x["lane"] == lid]
        out.append("")
        for x in data["skills"]:
            out += [p + "\n" for p in lr.get("skills", {}).get(x["name"], [])]
        out += [p + "\n" for p in lr.get("notes", [])]
    out += ["## Maintainer note", ""] + [p + "\n" for p in r["maintainer_note"]]
    out += ["## Recommended option", ""] + [p + "\n" for p in r["recommended_option"]]
    out += ["## Choice words for bots and scripted runs", "", r["choice_words_intro"], "", "| Skill | Question | Words |", "| --- | --- | --- |"]
    for x in data["skills"]:
        for q in x.get("choice_words") or []:
            out.append(f"| `/{x['name']}` | {q['question']} | " + " · ".join(f"`{w['word']}`" for w in q["words"]) + " |")
    out += ["", r["choice_words_example"], "", "## Machine-readable map", "", "```yaml", "starters:"]
    out += [f"  - {n}" for n in data["starter_options"]]
    for lane in data["lanes"]:
        lid = lane["id"]
        out += [f"{LANE_KEYS[lid]}:", "  skills:"] + [f"    - {x['name']}" for x in data["skills"] if x["lane"] == lid]
        subs = [x["name"] for x in data["subagents"] if x["lane"] == lid]
        out += ["  subagents:" + ("" if subs else " []")] + [f"    - {n}" for n in subs]
        if lid == "cross-cutting":
            out += ["  helpers:"] + [f"    - {h}" for h in r["helpers"]]
    out += ["```", ""]
    return "\n".join(out)


def expected(data: dict) -> dict[Path, str]:
    files = {TABLE: render_table(data), TABLE.parent / "index.yaml": render_index(data), ROUTING: render_routing(data)}
    for s in data["skills"]:
        files[PAGES / f"{s['name']}.md"] = render_page(s, data)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = load()
    errors = validate(data)
    files = expected(data)
    if args.check:
        for path, text in files.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                errors.append(f"{path.relative_to(ROOT)} is stale; run scripts/gen-skill-docs.py")
        if PAGES.is_dir():
            for p in PAGES.iterdir():
                if p not in files:
                    errors.append(f"{p.relative_to(ROOT)} is not generated from skills.yaml")
        for e in errors:
            print(e)
        if errors:
            return 1
        print("Skills reference matches docs/reference/skills.yaml")
        return 0
    if errors:
        for e in errors:
            print(e)
        return 1
    PAGES.mkdir(parents=True, exist_ok=True)
    for p in PAGES.iterdir():
        if p not in files:
            p.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"Wrote {len(files)} pages under docs/reference/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
